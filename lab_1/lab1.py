def machine_epsilon(dtype):
    eps = 1.0
    # Пока 1 + eps не станет отличимо от 1, делим eps пополам
    while dtype(1.0 + eps) != dtype(1.0):
        eps /= 2.0
    # Возвращаем последнее значение, при котором разница была (умножаем на 2)
    return eps * 2.0


