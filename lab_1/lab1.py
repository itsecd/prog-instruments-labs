import math  # Подключаем стандартную математическую библиотеку для точных вычислений

import matplotlib  # Подключаем библиотеку Matplotlib для построения графиков
import numpy as np  # Подключаем библиотеку NumPy для работы с массивами и математическими функциями

matplotlib.use("TkAgg")  # Указываем использовать графический движок TkAgg для отображения окон
import matplotlib.pyplot as plt  # Импортируем модуль pyplot для удобного построения графиков

print("ЛАБОРАТОРНАЯ РАБОТА №1")  # Выводим заголовок лабораторной работы


def my_func(x):  # Объявляем функцию для вычисления f(x) = ln(1+x)/x
    if abs(x) < 1e-300:  # Проверяем, не слишком ли близко x к нулю
        return 1.0  # Возвращаем предел функции при x -> 0, равный 1
    return np.log(1.0 + x) / x  # Вычисляем и возвращаем значение функции


x_vals = np.logspace(-1, -15, 15)  # Создаем массив из 15 значений x от 10^-1 до 10^-15

print("\n Задание 1: Сравнение float64 и float32 ")  # Выводим название первого задания
print(f"{'x':<10} {'float64':<20} {'float32':<20} {'Отн. ошибка':<15}")  # Выводим заголовки таблицы
print("-" * 65)  # Выводим разделительную линию из 65 символов

for x in x_vals:  # Запускаем цикл по всем значениям x
    res64 = my_func(np.float64(x))  # Вычисляем функцию с двойной точностью (float64)
    res32 = my_func(np.float32(x))  # Вычисляем функцию с одинарной точностью (float32)
    if res64 != 0:  # Проверяем, не равно ли значение float64 нулю
        rel_err = abs(res64 - res32) / abs(res64)  # Вычисляем относительную погрешность
    else:  # Если значение float64 равно нулю
        rel_err = 0.0  # Устанавливаем погрешность равной нулю
    print(f"{x:<10.1e} {res64:<20.10f} {res32:<20.10f} {rel_err:<15.2e}")  # Выводим строку таблицы


def machine_epsilon(dtype):  # Объявляем функцию для экспериментального поиска машинного эпсилона
    eps = 1.0  # Начинаем с начального значения 1.0
    while dtype(1.0 + eps) != dtype(1.0):  # Пока 1.0 + eps отличается от 1.0 в данном типе
        eps /= 2.0  # Делим eps пополам
    return eps * 2.0  # Возвращаем последнее значение, умноженное на 2


print("\n--- Задание 2: Машинный эпсилон ---")  # Выводим название второго задания
print(f"float64: {machine_epsilon(np.float64):.5e}")  # Выводим машинный эпсилон для float64
print(f"float32: {machine_epsilon(np.float32):.5e}")  # Выводим машинный эпсилон для float32


def my_ln_series(x, eps=1e-10):  # Объявляем функцию для вычисления ряда ln(1-x)
    term = -x  # Задаем первый член ряда a_1 = -x
    s = term  # Инициализируем сумму первым членом
    n = 2  # Начинаем счет со второго члена
    while abs(term) > eps:  # Пока модуль текущего члена больше заданной точности
        term *= x * (n - 1) / n  # Вычисляем следующий член по рекуррентной формуле
        s += term  # Добавляем текущий член к сумме
        n += 1  # Увеличиваем номер члена на единицу
    return s, n - 1  # Возвращаем сумму и количество учтенных членов


print("\n Задание 3: Ряд Тейлора для ln(1-x) ")  # Выводим название третьего задания
for x in [0.5, 1, 2]:  # Запускаем цикл по заданным значениям x
    if x >= 1:  # Проверяем, выходит ли x за область сходимости ряда
        print(f"x={x}: Ряд расходится (|x| < 1)")  # Сообщаем о расходимости ряда
        continue  # Переходим к следующему значению x
    for eps in [1e-6, 1e-10]:  # Запускаем цикл по заданным точностям
        approx, terms = my_ln_series(x, eps)  # Вычисляем приближенное значение и число членов
        exact = math.log(1 - x)  # Вычисляем точное значение через math.log
        print(
            f"x={x:<3} eps={eps:.0e}: approx={approx:.10f}, "  # Выводим приближенное значение
            f"exact={exact:.10f}, terms={terms}, error={abs(approx - exact):.2e}"
        )  # Выводим точное значение, число членов и ошибку

print("\n--- Задание 4: График погрешности ---")  # Выводим название четвертого задания

x_fixed = 0.9  # Задаем фиксированное значение x из области сходимости
exact_val = math.log(1 - x_fixed)  # Вычисляем точное значение функции

terms_list = []  # Создаем пустой список для хранения числа членов
errors_list = []  # Создаем пустой список для хранения погрешностей

term = -x_fixed  # Задаем первый член ряда
s = term  # Инициализируем сумму первым членом
n = 2  # Начинаем счет со второго члена
while n < 50:  # Запускаем цикл до 50 членов
    term *= x_fixed * (n - 1) / n  # Вычисляем следующий член ряда
    s += term  # Добавляем член к сумме
    n += 1  # Увеличиваем номер члена
    terms_list.append(n - 1)  # Добавляем число членов в список
    errors_list.append(abs(exact_val - s))  # Добавляем абсолютную погрешность в список

plt.figure(figsize=(8, 5))  # Создаем новое окно для графика размером 8 на 5
plt.semilogy(terms_list, errors_list, "o-", color="red")  # Строим график в полулогарифмическом масштабе
plt.title("Погрешность частичных сумм для ln(1-x) при x=0.9")  # Задаем заголовок графика
plt.xlabel("Число членов")  # Подписываем ось X
plt.ylabel("Абсолютная погрешность (лог. шкала)")  # Подписываем ось Y
plt.grid(True, which="both", linestyle="--")  # Включаем сетку для основных и промежуточных линий
plt.show()  # Отображаем построенный график на экране
